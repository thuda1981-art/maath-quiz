import json, random, hashlib, os

chapters = []
_cur_ch = None
_cur_l = None

def chapter(cid, num, title, color, icon):
    global _cur_ch
    _cur_ch = {"id": cid, "num": num, "title": title, "color": color, "icon": icon, "lessons": []}
    chapters.append(_cur_ch)

def lesson(lid, num, title, idea, rules, examples, tip):
    global _cur_l
    _cur_l = {"id": lid, "num": num, "title": title,
              "explain": {"idea": idea, "rules": rules,
                          "examples": [{"q": e[0], "steps": e[1], "a": e[2]} for e in examples],
                          "tip": tip},
              "questions": []}
    _cur_ch["lessons"].append(_cur_l)

def q(level, text, choices, answer, explanation, shuffle=True):
    assert answer in choices, (text, answer, choices)
    assert len(set(choices)) == len(choices), ("duplicate choice", text)
    qid = f"{_cur_l['id']}-{len(_cur_l['questions']) + 1}"
    ch = list(choices)
    if shuffle:
        random.Random(int(hashlib.md5(qid.encode()).hexdigest(), 16)).shuffle(ch)
    _cur_l["questions"].append({"id": qid, "level": level, "text": text, "choices": ch,
                                "answer": ch.index(answer), "explanation": explanation})

